-- Snowflake: load STG_MEMBER from RAW_MEMBER_FILE for one file.
-- Cleans text, converts dates, maps the country, repairs a DOB that lost its leading zero, validates each row,
-- derives AGE and STALE_MEMBER, sends rejected rows to QUARANTINE, and records data-quality warnings.
-- Set the two variables before running. Safe to re-run for the same file.

SET FILE_NAME = 'SKYPOINTS_MEMBERS_20240115.txt';
SET RUN_DATE = TO_DATE('2024-01-15');

CREATE OR REPLACE FUNCTION CLEAN_TEXT(V VARCHAR)
RETURNS VARCHAR
AS
$$
    IFF(UPPER(TRIM(V)) IN ('NULL', 'NONE', 'N/A', 'NA', 'NAN'), NULL, NULLIF(TRIM(V), ''))
$$;

CREATE OR REPLACE TEMPORARY TABLE STG_MEMBER_ALL AS
WITH C AS (
    SELECT
        R.FILE_NAME, R.FILE_DATE, R.ROW_NUM,
        CLEAN_TEXT(R.MEMBER_NAME) AS MEMBER_NAME,
        CLEAN_TEXT(R.MEMBER_ID) AS MEMBER_ID,
        TRY_TO_DATE(CLEAN_TEXT(R.ENROLLMENT_DATE), 'YYYYMMDD') AS ENROLLMENT_DATE,
        TRY_TO_DATE(CLEAN_TEXT(R.LAST_FLIGHT_DATE), 'YYYYMMDD') AS LAST_FLIGHT_DATE,
        UPPER(CLEAN_TEXT(R.TIER_CODE)) AS TIER_CODE,
        CLEAN_TEXT(R.AGENT_NAME) AS AGENT_NAME,
        UPPER(CLEAN_TEXT(R.STATE)) AS STATE,
        M.COUNTRY_ISO2 AS COUNTRY_ISO2,
        CLEAN_TEXT(R.POST_CODE) AS POST_CODE,
        TRY_TO_DATE(IFF(LENGTH(CLEAN_TEXT(R.DOB)) = 7, LPAD(CLEAN_TEXT(R.DOB), 8, '0'), CLEAN_TEXT(R.DOB)), 'DDMMYYYY') AS DOB,
        UPPER(CLEAN_TEXT(R.IS_ACTIVE)) AS IS_ACTIVE
    FROM RAW_MEMBER_FILE R
    LEFT JOIN COUNTRY_MAP M ON UPPER(TRIM(R.COUNTRY)) = M.RAW_VALUE
    WHERE R.FILE_NAME = $FILE_NAME AND R.ROW_NUM > 1
),
V AS (
    SELECT *,
        CASE
            WHEN MEMBER_NAME IS NULL THEN 'missing_member_name'
            WHEN MEMBER_ID IS NULL THEN 'missing_member_id'
            WHEN ENROLLMENT_DATE IS NULL THEN 'invalid_enrollment_date'
            WHEN LENGTH(MEMBER_NAME) > 255 OR LENGTH(MEMBER_ID) > 18 OR LENGTH(TIER_CODE) > 5
                 OR LENGTH(STATE) > 5 OR LENGTH(AGENT_NAME) > 255 OR LENGTH(IS_ACTIVE) > 1 THEN 'field_exceeds_max_length'
            WHEN COUNTRY_ISO2 IS NULL THEN 'unknown_or_missing_country'
        END AS REJECT_REASON
    FROM C
)
SELECT *,
    CASE
        WHEN REJECT_REASON IS NOT NULL THEN REJECT_REASON
        WHEN ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY ROW_NUM DESC) > 1 THEN 'duplicate_member_in_file'
    END AS FINAL_REASON
FROM V;

TRUNCATE TABLE STG_MEMBER;

DELETE FROM QUARANTINE WHERE SOURCE = 'member_file' AND FILE_NAME = $FILE_NAME
  AND REASON NOT IN ('unknown_record_type', 'column_count_mismatch');
DELETE FROM DQ_WARNING WHERE FILE_NAME = $FILE_NAME;

INSERT INTO STG_MEMBER
SELECT
    FILE_NAME, FILE_DATE, ROW_NUM, MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE,
    TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE,
    IFF(DOB IS NULL, NULL,
        DATEDIFF('year', DOB, $RUN_DATE) - IFF(TO_CHAR($RUN_DATE, 'MMDD') < TO_CHAR(DOB, 'MMDD'), 1, 0)) AS AGE,
    IFF(LAST_FLIGHT_DATE IS NULL, NULL, DATEDIFF('day', LAST_FLIGHT_DATE, $RUN_DATE) > 90) AS STALE_MEMBER
FROM STG_MEMBER_ALL
WHERE FINAL_REASON IS NULL;

INSERT INTO QUARANTINE (SOURCE, FILE_NAME, ROW_REF, REASON, DETAIL)
SELECT 'member_file', FILE_NAME, TO_VARCHAR(ROW_NUM), FINAL_REASON,
       'member_id=' || COALESCE(MEMBER_ID, '') || '; name=' || COALESCE(MEMBER_NAME, '')
FROM STG_MEMBER_ALL
WHERE FINAL_REASON IS NOT NULL;

INSERT INTO DQ_WARNING (FILE_NAME, CODE, ROW_COUNT, MESSAGE)
SELECT $FILE_NAME, 'dominant_dob', CNT, CNT || ' of ' || TOTAL || ' members share DOB ' || DOB || '; likely a placeholder, Age is unreliable'
FROM (
    SELECT DOB, CNT, TOTAL, ROW_NUMBER() OVER (ORDER BY CNT DESC) AS RN
    FROM (SELECT DOB, COUNT(*) AS CNT, SUM(COUNT(*)) OVER () AS TOTAL FROM STG_MEMBER WHERE DOB IS NOT NULL GROUP BY DOB)
)
WHERE RN = 1 AND TOTAL >= 3 AND CNT / TOTAL >= 0.5;

INSERT INTO DQ_WARNING (FILE_NAME, CODE, ROW_COUNT, MESSAGE)
SELECT $FILE_NAME, 'member_id_length_outlier', TOTAL - N,
       (TOTAL - N) || ' member ids differ in length from the usual ' || LEN || ' characters'
FROM (
    SELECT LEN, N, SUM(N) OVER () AS TOTAL, ROW_NUMBER() OVER (ORDER BY N DESC) AS RN
    FROM (SELECT LENGTH(MEMBER_ID) AS LEN, COUNT(*) AS N FROM STG_MEMBER GROUP BY 1)
)
WHERE RN = 1 AND TOTAL > N;

INSERT INTO DQ_WARNING (FILE_NAME, CODE, ROW_COUNT, MESSAGE)
SELECT $FILE_NAME, 'dob_leading_zero_repaired', N, '7-digit DOB left-padded to 8 (numeric type stripped the leading zero upstream)'
FROM (SELECT COUNT(*) AS N FROM RAW_MEMBER_FILE WHERE FILE_NAME = $FILE_NAME AND ROW_NUM > 1 AND LENGTH(TRIM(DOB)) = 7)
WHERE N > 0;

INSERT INTO DQ_WARNING (FILE_NAME, CODE, ROW_COUNT, MESSAGE)
SELECT $FILE_NAME, 'unknown_tier_code', N, 'Tier code outside GLD/SLV/PLT'
FROM (SELECT COUNT(*) AS N FROM STG_MEMBER WHERE TIER_CODE IS NOT NULL AND TIER_CODE NOT IN ('GLD', 'SLV', 'PLT'))
WHERE N > 0;

INSERT INTO DQ_WARNING (FILE_NAME, CODE, ROW_COUNT, MESSAGE)
SELECT $FILE_NAME, 'unknown_active_flag', N, 'Is_Active outside A/I'
FROM (SELECT COUNT(*) AS N FROM STG_MEMBER WHERE IS_ACTIVE IS NOT NULL AND IS_ACTIVE NOT IN ('A', 'I'))
WHERE N > 0;

INSERT INTO DQ_WARNING (FILE_NAME, CODE, ROW_COUNT, MESSAGE)
SELECT $FILE_NAME, 'same_name_different_member_id', N, 'The spec marks Member_Name as the key column, but the same name appears under different ids'
FROM (SELECT COUNT(*) AS N FROM (SELECT MEMBER_NAME FROM STG_MEMBER GROUP BY MEMBER_NAME HAVING COUNT(DISTINCT MEMBER_ID) > 1))
WHERE N > 0;