-- Snowflake: flatten the JSON redemption feed into FACT_REDEMPTION, quarantine bad transactions, and join the
-- result to the member profile. Each document holds one member and an array of redemptions; LATERAL FLATTEN
-- turns the array into rows. Rejected: missing ids, invalid date, unknown status, invalid miles, duplicate
-- transaction id, and members with no profile. Set FILE_NAME before running. Safe to re-run for the same file.

SET FILE_NAME = 'SKYPOINTS_REDEMPTIONS_20240115.json';

DELETE FROM QUARANTINE WHERE SOURCE = 'redemption_feed' AND FILE_NAME = $FILE_NAME;

CREATE OR REPLACE TEMPORARY TABLE REDEMPTION_FLAT AS
WITH F AS (
    SELECT
        NULLIF(TRIM(F.VALUE:txn_id::VARCHAR), '') AS TXN_ID,
        NULLIF(TRIM(R.PAYLOAD:member_id::VARCHAR), '') AS MEMBER_ID,
        TRY_TO_DATE(F.VALUE:txn_date::VARCHAR, 'YYYYMMDD') AS TXN_DATE,
        F.VALUE:partner::VARCHAR AS PARTNER,
        TRY_TO_NUMBER(F.VALUE:miles_redeemed::VARCHAR) AS MILES_REDEEMED,
        UPPER(TRIM(F.VALUE:status::VARCHAR)) AS STATUS,
        COALESCE(TRY_TO_DATE(R.PAYLOAD:feed_date::VARCHAR, 'YYYYMMDD'), R.FEED_DATE) AS FEED_DATE,
        R.FILE_NAME AS SOURCE_FILE,
        R.LOADED_AT AS LOADED_AT,
        F.SEQ AS SEQ,
        F.INDEX AS POS
    FROM RAW_REDEMPTION_JSON R,
         LATERAL FLATTEN(INPUT => R.PAYLOAD:redemptions) F
    WHERE R.FILE_NAME = $FILE_NAME
),
V AS (
    SELECT *,
        CASE
            WHEN MEMBER_ID IS NULL THEN 'missing_member_id'
            WHEN TXN_ID IS NULL THEN 'missing_txn_id'
            WHEN TXN_DATE IS NULL THEN 'invalid_txn_date'
            WHEN STATUS IS NULL OR STATUS NOT IN ('COMPLETED', 'PENDING', 'CANCELLED') THEN 'invalid_status'
            WHEN MILES_REDEEMED IS NULL OR MILES_REDEEMED < 0 THEN 'invalid_miles'
        END AS REASON
    FROM F
),
D AS (
    SELECT *,
        CASE
            WHEN REASON IS NOT NULL THEN REASON
            WHEN ROW_NUMBER() OVER (PARTITION BY TXN_ID ORDER BY LOADED_AT, SEQ, POS) > 1 THEN 'duplicate_txn_id'
        END AS FINAL_REASON
    FROM V
)
SELECT D.*,
    CASE
        WHEN D.FINAL_REASON IS NOT NULL THEN D.FINAL_REASON
        WHEN I.MEMBER_ID IS NULL THEN 'unknown_member'
    END AS OUTCOME
FROM D
LEFT JOIN MEMBER_COUNTRY_INDEX I ON I.MEMBER_ID = D.MEMBER_ID;

MERGE INTO FACT_REDEMPTION T
USING (SELECT * FROM REDEMPTION_FLAT WHERE OUTCOME IS NULL) S
ON T.TXN_ID = S.TXN_ID
WHEN MATCHED THEN UPDATE SET
    MEMBER_ID = S.MEMBER_ID, TXN_DATE = S.TXN_DATE, PARTNER = S.PARTNER, MILES_REDEEMED = S.MILES_REDEEMED,
    STATUS = S.STATUS, FEED_DATE = S.FEED_DATE, SOURCE_FILE = S.SOURCE_FILE
WHEN NOT MATCHED THEN INSERT (TXN_ID, MEMBER_ID, TXN_DATE, PARTNER, MILES_REDEEMED, STATUS, FEED_DATE, SOURCE_FILE)
VALUES (S.TXN_ID, S.MEMBER_ID, S.TXN_DATE, S.PARTNER, S.MILES_REDEEMED, S.STATUS, S.FEED_DATE, S.SOURCE_FILE);

INSERT INTO QUARANTINE (SOURCE, FILE_NAME, ROW_REF, REASON, DETAIL)
SELECT 'redemption_feed', SOURCE_FILE, COALESCE(TXN_ID, '?'), OUTCOME,
       'member_id=' || COALESCE(MEMBER_ID, '') || '; status=' || COALESCE(STATUS, '')
FROM REDEMPTION_FLAT
WHERE OUTCOME IS NOT NULL;

SELECT I.COUNTRY_ISO2, F.PARTNER,
       COUNT(*) AS TRANSACTIONS,
       SUM(IFF(F.STATUS = 'COMPLETED', F.MILES_REDEEMED, 0)) AS MILES_COMPLETED,
       SUM(IFF(F.STATUS = 'PENDING', F.MILES_REDEEMED, 0)) AS MILES_PENDING
FROM FACT_REDEMPTION F
JOIN MEMBER_COUNTRY_INDEX I ON I.MEMBER_ID = F.MEMBER_ID
GROUP BY 1, 2
ORDER BY 1, 2;