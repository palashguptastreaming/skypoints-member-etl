-- Snowflake: split staged members into one table per country with latest record wins.
-- A staged row is applied only if the member index does not already hold a newer file for that member, so an
-- old file replayed later cannot move a member back. Every effective member is removed from all country
-- tables and inserted into the table of their current country, in one transaction, so a re-run gives the
-- same result. One table per country in COUNTRY_MAP; a new country needs a table, a delete and an insert here.

BEGIN TRANSACTION;

CREATE OR REPLACE TEMPORARY TABLE BATCH_EFF AS
SELECT S.*
FROM STG_MEMBER S
LEFT JOIN MEMBER_COUNTRY_INDEX I ON I.MEMBER_ID = S.MEMBER_ID
WHERE I.MEMBER_ID IS NULL OR I.FILE_DATE <= S.FILE_DATE;

DELETE FROM TGT_MEMBER_AE WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM BATCH_EFF);
DELETE FROM TGT_MEMBER_AU WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM BATCH_EFF);
DELETE FROM TGT_MEMBER_CA WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM BATCH_EFF);
DELETE FROM TGT_MEMBER_GB WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM BATCH_EFF);
DELETE FROM TGT_MEMBER_IN WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM BATCH_EFF);
DELETE FROM TGT_MEMBER_PH WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM BATCH_EFF);
DELETE FROM TGT_MEMBER_SG WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM BATCH_EFF);
DELETE FROM TGT_MEMBER_US WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM BATCH_EFF);

INSERT INTO TGT_MEMBER_AE (MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, SOURCE_FILE, FILE_DATE)
SELECT MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, FILE_NAME, FILE_DATE FROM BATCH_EFF WHERE COUNTRY_ISO2 = 'AE';

INSERT INTO TGT_MEMBER_AU (MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, SOURCE_FILE, FILE_DATE)
SELECT MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, FILE_NAME, FILE_DATE FROM BATCH_EFF WHERE COUNTRY_ISO2 = 'AU';

INSERT INTO TGT_MEMBER_CA (MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, SOURCE_FILE, FILE_DATE)
SELECT MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, FILE_NAME, FILE_DATE FROM BATCH_EFF WHERE COUNTRY_ISO2 = 'CA';

INSERT INTO TGT_MEMBER_GB (MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, SOURCE_FILE, FILE_DATE)
SELECT MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, FILE_NAME, FILE_DATE FROM BATCH_EFF WHERE COUNTRY_ISO2 = 'GB';

INSERT INTO TGT_MEMBER_IN (MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, SOURCE_FILE, FILE_DATE)
SELECT MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, FILE_NAME, FILE_DATE FROM BATCH_EFF WHERE COUNTRY_ISO2 = 'IN';

INSERT INTO TGT_MEMBER_PH (MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, SOURCE_FILE, FILE_DATE)
SELECT MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, FILE_NAME, FILE_DATE FROM BATCH_EFF WHERE COUNTRY_ISO2 = 'PH';

INSERT INTO TGT_MEMBER_SG (MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, SOURCE_FILE, FILE_DATE)
SELECT MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, FILE_NAME, FILE_DATE FROM BATCH_EFF WHERE COUNTRY_ISO2 = 'SG';

INSERT INTO TGT_MEMBER_US (MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, SOURCE_FILE, FILE_DATE)
SELECT MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY_ISO2, POST_CODE, DOB, IS_ACTIVE, AGE, STALE_MEMBER, FILE_NAME, FILE_DATE FROM BATCH_EFF WHERE COUNTRY_ISO2 = 'US';

MERGE INTO MEMBER_COUNTRY_INDEX T
USING BATCH_EFF S
ON T.MEMBER_ID = S.MEMBER_ID
WHEN MATCHED THEN UPDATE SET COUNTRY_ISO2 = S.COUNTRY_ISO2, FILE_DATE = S.FILE_DATE
WHEN NOT MATCHED THEN INSERT (MEMBER_ID, COUNTRY_ISO2, FILE_DATE) VALUES (S.MEMBER_ID, S.COUNTRY_ISO2, S.FILE_DATE);

COMMIT;