-- Snowflake DDL for the SkyPoints pipeline: raw, support, staging and one table per country, plus the country mapping.
-- Same design as the DuckDB version in sql/. PRIMARY KEY is informational in Snowflake (not enforced),
-- so uniqueness is guaranteed by the load logic. These scripts are not run by the Python tests.

CREATE TABLE IF NOT EXISTS RAW_MEMBER_FILE (
    FILE_NAME        VARCHAR NOT NULL,
    FILE_DATE        DATE NOT NULL,
    ROW_NUM          NUMBER NOT NULL,
    MEMBER_NAME      VARCHAR,
    MEMBER_ID        VARCHAR,
    ENROLLMENT_DATE  VARCHAR,
    LAST_FLIGHT_DATE VARCHAR,
    TIER_CODE        VARCHAR,
    AGENT_NAME       VARCHAR,
    STATE            VARCHAR,
    COUNTRY          VARCHAR,
    POST_CODE        VARCHAR,
    DOB              VARCHAR,
    IS_ACTIVE        VARCHAR,
    LOADED_AT        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_REDEMPTION_JSON (
    FILE_NAME VARCHAR NOT NULL,
    FEED_DATE DATE NOT NULL,
    PAYLOAD   VARIANT NOT NULL,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS COUNTRY_MAP (
    RAW_VALUE    VARCHAR PRIMARY KEY,
    COUNTRY_ISO2 VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS QUARANTINE (
    SOURCE    VARCHAR NOT NULL,
    FILE_NAME VARCHAR NOT NULL,
    ROW_REF   VARCHAR,
    REASON    VARCHAR NOT NULL,
    DETAIL    VARCHAR,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS DQ_WARNING (
    FILE_NAME VARCHAR NOT NULL,
    CODE      VARCHAR NOT NULL,
    ROW_COUNT NUMBER NOT NULL,
    MESSAGE   VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS MEMBER_COUNTRY_INDEX (
    MEMBER_ID    VARCHAR PRIMARY KEY,
    COUNTRY_ISO2 VARCHAR NOT NULL,
    FILE_DATE    DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS STG_MEMBER (
    FILE_NAME        VARCHAR NOT NULL,
    FILE_DATE        DATE NOT NULL,
    ROW_NUM          NUMBER NOT NULL,
    MEMBER_ID        VARCHAR NOT NULL,
    MEMBER_NAME      VARCHAR NOT NULL,
    ENROLLMENT_DATE  DATE NOT NULL,
    LAST_FLIGHT_DATE DATE,
    TIER_CODE        VARCHAR,
    AGENT_NAME       VARCHAR,
    STATE            VARCHAR,
    COUNTRY_ISO2     VARCHAR NOT NULL,
    POST_CODE        VARCHAR,
    DOB              DATE,
    IS_ACTIVE        VARCHAR,
    AGE              NUMBER,
    STALE_MEMBER     BOOLEAN
);

CREATE TABLE IF NOT EXISTS TGT_MEMBER_TEMPLATE (
    MEMBER_ID        VARCHAR PRIMARY KEY,
    MEMBER_NAME      VARCHAR NOT NULL,
    ENROLLMENT_DATE  DATE NOT NULL,
    LAST_FLIGHT_DATE DATE,
    TIER_CODE        VARCHAR,
    AGENT_NAME       VARCHAR,
    STATE            VARCHAR,
    COUNTRY_ISO2     VARCHAR NOT NULL,
    POST_CODE        VARCHAR,
    DOB              DATE,
    IS_ACTIVE        VARCHAR,
    AGE              NUMBER,
    STALE_MEMBER     BOOLEAN,
    SOURCE_FILE      VARCHAR NOT NULL,
    FILE_DATE        DATE NOT NULL,
    LOADED_AT        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS TGT_MEMBER_AE LIKE TGT_MEMBER_TEMPLATE;
CREATE TABLE IF NOT EXISTS TGT_MEMBER_AU LIKE TGT_MEMBER_TEMPLATE;
CREATE TABLE IF NOT EXISTS TGT_MEMBER_CA LIKE TGT_MEMBER_TEMPLATE;
CREATE TABLE IF NOT EXISTS TGT_MEMBER_GB LIKE TGT_MEMBER_TEMPLATE;
CREATE TABLE IF NOT EXISTS TGT_MEMBER_IN LIKE TGT_MEMBER_TEMPLATE;
CREATE TABLE IF NOT EXISTS TGT_MEMBER_PH LIKE TGT_MEMBER_TEMPLATE;
CREATE TABLE IF NOT EXISTS TGT_MEMBER_SG LIKE TGT_MEMBER_TEMPLATE;
CREATE TABLE IF NOT EXISTS TGT_MEMBER_US LIKE TGT_MEMBER_TEMPLATE;

CREATE TABLE IF NOT EXISTS FACT_REDEMPTION (
    TXN_ID         VARCHAR PRIMARY KEY,
    MEMBER_ID      VARCHAR NOT NULL,
    TXN_DATE       DATE NOT NULL,
    PARTNER        VARCHAR,
    MILES_REDEEMED NUMBER NOT NULL,
    STATUS         VARCHAR NOT NULL,
    FEED_DATE      DATE NOT NULL,
    SOURCE_FILE    VARCHAR NOT NULL
);

